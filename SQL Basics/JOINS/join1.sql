------ JOINS IN SQL ---
--- JOINS IN SQL IS USED FOR LINKING TWO OR MORE TABLES IF THEY HAVE A SAME OR COMMON COLUMN . FOREIGN KEY IS NOT NECESSARY FOR JOINS . 
--- TYPES OF JOINS : INNER JOIN , LEFT OUTER JOIN , RIGHT OUTER JOIN , SELF JOIN , CROSS JOIN ----

CREATE DATABASE IF NOT EXISTS ecom ;
use ecom ;
CREATE TABLE IF NOT EXISTS customers( id INT PRIMARY KEY , name VARCHAR(100) ) ;
CREATE TABLE IF NOT EXISTS orderes( id INT PRIMARY KEY , order_name VARCHAR(100) );
