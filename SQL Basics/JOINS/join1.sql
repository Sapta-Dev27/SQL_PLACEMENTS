--- INNER JOIN : USED IN GETTING THE ROWS THAT HAVE THE SAME MATCHING VALUES IN BOTH THE TABLES . i.e : INTERSECTION OF BOTH TABLES -- 

SELECT * from customers INNER JOIN orderes ON customers.id = orderes.id;


---- LEFT JOIN : USED FOR GETTING ALL THE ROWS FROM THE LEFT TABLE ALONG WITH THE MATCHING VALUES FROM THE RIGHT TABLE . IF ANY ROW DOESNOT HAVE
---- A MATCH FROM THE RIGHT TABLE THEN THAT COLUMN IN RIGHT TABLE IS SET TO BE NULL .
---- LEFT TABLE => BEFORE LEFT JOIN KEYWORD , RIGHT TABLE => AFTER LEFT JOIN KEYWORD 


SELECT * from customers LEFT JOIN orderes ON customers.id = orderes.id;
SELECT * from orderes LEFT JOIN customers ON orderes.id = customers.id ;


----- RIGHT JOIN : USED FOR GETTING ALL THE ROWS FROM THE RIGHT TABLE ALONG WITH THE MATCHING  VALUES FROM THE LEFT TABLE . IF ANY ROW DOESNOT HAVE
---- A MATCH FROM THE LEFT TABLE THEN THAT COLUMN IN THE LEFT TABLE IS SET TO BE NULL . LEFT TABLE => LEFT OF RIGHT JOIN KEYWORD , RIGHT TABLE => RIGHT OF JOIN KEYWORD

SELECT * from customers RIGHT JOIN orderes ON customers.id = orderes.id;
SELECT * from orderes RIGHT JOIN customers ON customers.id = orderes.id ;